// Generates a Supabase seed migration from the bundled message catalogs.
//
//   node scripts/generate-translations-seed.mjs
//
// Reads messages/{id,en}.json (namespace -> key -> string) and writes a
// `... _seed_translations.sql` migration that upserts every string into
// public.translation_messages. Re-runnable: existing rows are left untouched
// (`on conflict do nothing`), so it never overwrites values edited in the CMS.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const locales = ["id", "en"];

/** Escape a value for a single-quoted Postgres string literal. */
const sql = (v) => `'${String(v).replace(/'/g, "''")}'`;

const rows = [];
for (const locale of locales) {
  const catalog = JSON.parse(
    readFileSync(join(root, "messages", `${locale}.json`), "utf8"),
  );
  for (const [namespace, entries] of Object.entries(catalog)) {
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== "string") {
        throw new Error(
          `Non-string message at ${namespace}.${key} (${locale}); only flat namespace/key/string catalogs are supported.`,
        );
      }
      rows.push(`  (${sql(namespace)}, ${sql(key)}, ${sql(locale)}, ${sql(value)})`);
    }
  }
}

const out = `-- AUTO-GENERATED by scripts/generate-translations-seed.mjs — do not edit by hand.
-- Seeds public.translation_messages from messages/{id,en}.json.
-- Re-runnable: existing (namespace, key, locale) rows are kept as-is.

insert into public.translation_messages (namespace, key, locale, value) values
${rows.join(",\n")}
on conflict (namespace, key, locale) do nothing;
`;

const target = join(
  root,
  "supabase",
  "migrations",
  "20260610090100_seed_translations.sql",
);
writeFileSync(target, out, "utf8");
console.log(`Wrote ${rows.length} rows -> ${target}`);
